begin;

-- Consolidates specialty values onto doctor_profiles and moves both Doctor
-- audit histories into doctor_admin_audit_logs before removing old tables.

-- Rebuild the combined Doctor view before removing columns it currently reads.
drop view if exists public.doctor_directory;

-- Move specialty values onto the one Doctor profile row.
alter table public.doctor_profiles
  add column if not exists specialty text not null default '';

update public.doctor_profiles d
set specialty=coalesce(
  nullif(btrim(d.custom_specialization),''),
  (select nullif(btrim(m.specialization_name),'')
   from public.medical_specializations m where m.id=d.specialization_id),
  nullif(btrim(d.sub_specialization),''),
  ''
);

-- Combine profile corrections and account access changes into one audit table.
create table if not exists public.doctor_admin_audit_logs (
  id bigint generated by default as identity primary key,
  doctor_staff_id text not null references public.staff(id) on delete cascade,
  changed_by uuid not null references auth.users(id) on delete restrict,
  event_type text not null check(event_type in ('profile','account')),
  change_reason text not null,
  previous_state jsonb not null default '{}'::jsonb,
  new_state jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists doctor_admin_audit_logs_staff_created_idx
  on public.doctor_admin_audit_logs(doctor_staff_id,created_at desc);
alter table public.doctor_admin_audit_logs enable row level security;
grant select on public.doctor_admin_audit_logs to authenticated;
drop policy if exists doctor_admin_audit_admin_read on public.doctor_admin_audit_logs;
create policy doctor_admin_audit_admin_read on public.doctor_admin_audit_logs for select to authenticated using (
  exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role='admin' and p.active=true)
);

insert into public.doctor_admin_audit_logs(
  doctor_staff_id,changed_by,event_type,change_reason,previous_state,new_state,created_at
)
select doctor_staff_id,changed_by,'profile',change_reason,previous_profile,new_profile,created_at
from public.doctor_profile_audit_logs;

insert into public.doctor_admin_audit_logs(
  doctor_staff_id,changed_by,event_type,change_reason,previous_state,new_state,created_at
)
select doctor_staff_id,changed_by,'account',change_reason,
  jsonb_build_object('active',was_active),jsonb_build_object('active',is_active),created_at
from public.doctor_account_audit_logs;

drop function if exists public.nurse_list_active_doctors(date);
create function public.nurse_list_active_doctors(p_appointment_date date)
returns table(
  staff_id text, user_id uuid, full_name text, professional_title text,
  specialization text, department text, professional_description text,
  doctor_identifier text, available_slots time[]
)
language plpgsql stable security definer set search_path=pg_catalog,public as $$
begin
  if not public.erecpass_is_active_nurse(auth.uid()) then
    raise exception 'Active Nurse access is required.' using errcode='42501';
  end if;
  return query
  select s.id,s.user_id,s.name,d.professional_title,
    coalesce(nullif(btrim(d.specialty),''),'Not specified'),
    d.department,d.professional_description,d.doctor_identifier,
    coalesce((select array_agg(x.appointment_time order by x.appointment_time)
      from public.get_available_appointment_slots(s.id,p_appointment_date) x),array[]::time[])
  from public.staff s
  join public.profiles p on p.id=s.user_id and p.role='staff' and p.active=true
  join public.doctor_profiles d on d.staff_id=s.id and d.consultation_available=true
  where s.active=true and s.account_type='doctor'
  order by s.name;
end $$;
revoke all on function public.nurse_list_active_doctors(date) from public,anon;
grant execute on function public.nurse_list_active_doctors(date) to authenticated;

drop function if exists public.admin_update_doctor_profile(text,uuid,text,text,text,text,text);
create function public.admin_update_doctor_profile(
  p_staff_id text,p_specialty text,p_department text,p_description text,p_credentials text,p_reason text
) returns public.doctor_profiles
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_old jsonb;
  v_new public.doctor_profiles%rowtype;
begin
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin' and p.active=true) then
    raise exception 'Active Admin access is required.' using errcode='42501';
  end if;
  if nullif(btrim(coalesce(p_reason,'')),'') is null then raise exception 'An audit reason is required.' using errcode='22023'; end if;
  if nullif(btrim(coalesce(p_specialty,'')),'') is null then raise exception 'Enter a Doctor specialty.' using errcode='22023'; end if;
  if not exists(select 1 from public.staff s join public.profiles p on p.id=s.user_id
    where s.id=p_staff_id and s.active=true and s.account_type='doctor' and p.role='staff' and p.active=true) then
    raise exception 'Active Doctor profile not found.' using errcode='P0002';
  end if;
  select to_jsonb(d) into v_old from public.doctor_profiles d where d.staff_id=p_staff_id for update;
  insert into public.doctor_profiles(staff_id,specialty,department,professional_description,professional_credentials,admin_override_locked)
  values(p_staff_id,btrim(p_specialty),btrim(coalesce(p_department,'')),btrim(coalesce(p_description,'')),btrim(coalesce(p_credentials,'')),true)
  on conflict(staff_id) do update set specialty=excluded.specialty,department=excluded.department,
    professional_description=excluded.professional_description,professional_credentials=excluded.professional_credentials,
    admin_override_locked=true
  returning * into v_new;
  insert into public.doctor_admin_audit_logs(doctor_staff_id,changed_by,event_type,change_reason,previous_state,new_state)
  values(p_staff_id,auth.uid(),'profile',btrim(p_reason),coalesce(v_old,'{}'::jsonb),to_jsonb(v_new));
  return v_new;
end $$;
revoke all on function public.admin_update_doctor_profile(text,text,text,text,text,text) from public,anon;
grant execute on function public.admin_update_doctor_profile(text,text,text,text,text,text) to authenticated;

create or replace function public.admin_set_doctor_active(p_staff_id text,p_active boolean,p_reason text)
returns boolean language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_user_id uuid; v_was_active boolean;
begin
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin' and p.active=true) then
    raise exception 'Active Admin access is required.' using errcode='42501';
  end if;
  if nullif(btrim(coalesce(p_reason,'')),'') is null then raise exception 'An audit reason is required.' using errcode='22023'; end if;
  select s.user_id,s.active into v_user_id,v_was_active from public.staff s
  join public.profiles p on p.id=s.user_id and p.role='staff'
  where s.id=p_staff_id and s.account_type='doctor' for update of s;
  if not found then raise exception 'Doctor account not found.' using errcode='P0002'; end if;
  update public.staff set active=p_active where id=p_staff_id;
  update public.profiles set active=p_active where id=v_user_id;
  insert into public.doctor_admin_audit_logs(doctor_staff_id,changed_by,event_type,change_reason,previous_state,new_state)
  values(p_staff_id,auth.uid(),'account',btrim(p_reason),jsonb_build_object('active',v_was_active),jsonb_build_object('active',p_active));
  return p_active;
end $$;
revoke all on function public.admin_set_doctor_active(text,boolean,text) from public,anon;
grant execute on function public.admin_set_doctor_active(text,boolean,text) to authenticated;

-- The old audit data has been copied above; remove the duplicate tables.
drop table public.doctor_profile_audit_logs;
drop table public.doctor_account_audit_logs;

-- Specialty text now lives on doctor_profiles, so the lookup table and its
-- former relationship columns are no longer needed.
alter table public.doctor_profiles
  drop column if exists specialization_id,
  drop column if exists custom_specialization,
  drop column if exists sub_specialization;
drop table public.medical_specializations;

create view public.doctor_directory
with (security_invoker = true)
as
select
  s.id as staff_id,
  s.name as doctor_name,
  s.active as staff_active,
  d.professional_title,
  coalesce(nullif(btrim(d.specialty),''),'Not specified') as specialization,
  d.department,
  d.professional_description,
  d.professional_credentials,
  d.doctor_identifier,
  d.consultation_available,
  d.admin_override_locked,
  coalesce(weekly.schedule,'[]'::jsonb) as weekly_availability,
  coalesce(time_off.dates,'[]'::jsonb) as unavailability
from public.staff s
join public.doctor_profiles d on d.staff_id=s.id
left join lateral (
  select jsonb_agg(jsonb_build_object(
    'day_of_week',a.day_of_week,'is_available',a.is_available,
    'start_time',a.start_time,'end_time',a.end_time,'break_start',a.break_start,'break_end',a.break_end,
    'appointment_duration_minutes',a.appointment_duration_minutes,
    'max_appointments_per_slot',a.max_appointments_per_slot
  ) order by a.day_of_week) as schedule
  from public.staff_availability a where a.staff_id=s.id
) weekly on true
left join lateral (
  select jsonb_agg(jsonb_build_object('date',u.unavailable_date,'start_time',u.start_time,'end_time',u.end_time)
    order by u.unavailable_date,u.start_time) as dates
  from public.staff_unavailability u where u.staff_id=s.id
) time_off on true
where s.account_type='doctor';
grant select on public.doctor_directory to authenticated;

commit;
