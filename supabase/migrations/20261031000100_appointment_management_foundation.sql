-- eRecPass appointment management foundation.
-- Additive: preserves existing appointment records and legacy columns.
-- Legacy fields and records are preserved; unique provider names are linked below.
begin;

alter table public.appointments
  add column if not exists provider_staff_id text,
  add column if not exists appointment_time time,
  add column if not exists appointment_duration_minutes integer,
  add column if not exists rejection_reason text,
  add column if not exists staff_note text,
  add column if not exists last_decision_by uuid references auth.users(id) on delete set null,
  add column if not exists last_decision_at timestamptz;

do $$
begin
  if not exists (select 1 from pg_constraint where conrelid='public.appointments'::regclass and conname='appointments_provider_staff_id_fkey') then
    alter table public.appointments add constraint appointments_provider_staff_id_fkey
      foreign key (provider_staff_id) references public.staff(id) on delete set null;
  end if;
end $$;

create index if not exists appointments_provider_date_idx
  on public.appointments(provider_staff_id, appointment_date, appointment_time);
create index if not exists appointments_status_provider_date_idx
  on public.appointments(status, provider_staff_id, appointment_date);

-- Assign existing date-only requests where the saved provider name maps to
-- exactly one active Staff account. Ambiguous or unmatched names stay unassigned.
with unique_staff_names as (
  select lower(btrim(s.name)) as name_key, min(s.id) as staff_id
  from public.staff s
  join public.profiles p on p.id=s.user_id and p.role='staff' and p.active=true
  where s.active=true and nullif(btrim(s.name),'') is not null
  group by lower(btrim(s.name))
  having count(*)=1
)
update public.appointments a
set provider_staff_id=u.staff_id
from unique_staff_names u
where a.provider_staff_id is null
  and nullif(btrim(a.doctor),'') is not null
  and lower(btrim(a.doctor))=u.name_key;

create table if not exists public.staff_availability (
  id bigint generated by default as identity primary key,
  staff_id text not null references public.staff(id) on delete cascade,
  day_of_week smallint not null check(day_of_week between 0 and 6),
  start_time time not null,
  end_time time not null,
  break_start time,
  break_end time,
  appointment_duration_minutes integer not null default 30 check(appointment_duration_minutes between 5 and 240),
  max_appointments_per_slot integer not null default 1 check(max_appointments_per_slot between 1 and 100),
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint staff_availability_valid_hours check(start_time < end_time),
  constraint staff_availability_valid_break check(
    (break_start is null and break_end is null) or
    (break_start is not null and break_end is not null and break_start < break_end
      and break_start >= start_time and break_end <= end_time)
  ),
  constraint staff_availability_staff_day_key unique(staff_id, day_of_week)
);

create table if not exists public.staff_unavailability (
  id bigint generated by default as identity primary key,
  staff_id text not null references public.staff(id) on delete cascade,
  unavailable_date date not null,
  start_time time,
  end_time time,
  reason text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint staff_unavailability_valid_hours check(
    (start_time is null and end_time is null) or
    (start_time is not null and end_time is not null and start_time < end_time)
  )
);
create index if not exists staff_unavailability_staff_date_idx
  on public.staff_unavailability(staff_id, unavailable_date);

create table if not exists public.medical_specializations (
