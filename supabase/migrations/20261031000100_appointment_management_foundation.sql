  specialization_id uuid references public.medical_specializations(id) on delete set null,
  sub_specialization text,
  department text not null default '',
  professional_description text not null default '',
  consultation_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
