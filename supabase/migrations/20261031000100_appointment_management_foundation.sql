-- Serialize booking attempts by provider/day and validate all assigned active slots.
create or replace function public.erecpass_validate_appointment_slot()
returns trigger language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_schedule public.staff_availability%rowtype;
  v_duration integer;
  v_end_time time;
  v_same_slot_count integer;
begin
  if new.provider_staff_id is null
     or lower(trim(coalesce(new.status,''))) not in ('pending','pending approval','approved') then
    return new;
  end if;
  if new.appointment_date is null or new.appointment_time is null then
    raise exception 'Assigned appointments require a date and time.' using errcode='22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(new.provider_staff_id||'|'||new.appointment_date::text,0));
  select a.* into v_schedule
  from public.staff_availability a
  join public.staff s on s.id=a.staff_id and s.active=true
  join public.profiles p on p.id=s.user_id and p.role='staff' and p.active=true
  where a.staff_id=new.provider_staff_id
    and a.day_of_week=extract(dow from new.appointment_date)::smallint
    and a.is_available=true
  for share of a;
  if not found then raise exception 'The selected provider is not available on that day.' using errcode='22023'; end if;

  v_duration:=coalesce(new.appointment_duration_minutes,v_schedule.appointment_duration_minutes);
  if v_duration<5 or v_duration>240 then raise exception 'Invalid appointment duration.' using errcode='22023'; end if;
  new.appointment_duration_minutes:=v_duration;
  v_end_time:=new.appointment_time+make_interval(mins=>v_duration);
  if (new.appointment_date+new.appointment_time+make_interval(mins=>v_duration))::date>new.appointment_date then
    raise exception 'Appointments cannot extend past midnight.' using errcode='22023';
  end if;
  if new.appointment_time<v_schedule.start_time or v_end_time>v_schedule.end_time then
    raise exception 'The selected time is outside the provider working hours.' using errcode='22023';
  end if;
  if v_schedule.break_start is not null and new.appointment_time<v_schedule.break_end and v_end_time>v_schedule.break_start then
    raise exception 'The selected time overlaps the provider break.' using errcode='22023';
  end if;
  if (new.appointment_date+new.appointment_time)<=(now() at time zone 'Asia/Manila') then
    raise exception 'Appointments must be scheduled in the future (Asia/Manila time).' using errcode='22023';
  end if;
  if exists (
    select 1 from public.staff_unavailability u
    where u.staff_id=new.provider_staff_id and u.unavailable_date=new.appointment_date
      and (u.start_time is null or (new.appointment_time<u.end_time and v_end_time>u.start_time))
  ) then raise exception 'The provider is unavailable at the selected time.' using errcode='22023'; end if;

  select count(*) into v_same_slot_count from public.appointments a
  where a.provider_staff_id=new.provider_staff_id and a.appointment_date=new.appointment_date
    and a.appointment_time=new.appointment_time
    and lower(trim(a.status)) in ('pending','pending approval','approved')
    and a.id is distinct from new.id;
  if v_same_slot_count>=v_schedule.max_appointments_per_slot then
    raise exception 'This appointment slot is fully booked.' using errcode='23P01';
  end if;
  if exists (
    select 1 from public.appointments a
    where a.provider_staff_id=new.provider_staff_id and a.appointment_date=new.appointment_date
      and a.appointment_time is not null and a.appointment_time<>new.appointment_time
      and lower(trim(a.status)) in ('pending','pending approval','approved')
      and a.id is distinct from new.id
      and a.appointment_time<v_end_time
      and (a.appointment_time+make_interval(mins=>coalesce(a.appointment_duration_minutes,v_duration)))>new.appointment_time
  ) then raise exception 'The selected time overlaps another appointment.' using errcode='23P01'; end if;
  return new;
end $$;
revoke all on function public.erecpass_validate_appointment_slot() from public, anon, authenticated;
drop trigger if exists appointments_validate_slot on public.appointments;
create trigger appointments_validate_slot
before insert or update of provider_staff_id,appointment_date,appointment_time,appointment_duration_minutes,status
on public.appointments for each row execute function public.erecpass_validate_appointment_slot();

-- Return only open slots; patients cannot read other patients' bookings.
create or replace function public.get_available_appointment_slots(
  p_staff_id text,
  p_appointment_date date
) returns table(appointment_time time, remaining_capacity integer)
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_schedule public.staff_availability%rowtype;
  v_slot time;
  v_slot_end time;
  v_booked integer;
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode='28000'; end if;
  if p_appointment_date is null or p_appointment_date<(now() at time zone 'Asia/Manila')::date then
    return;
  end if;
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.active=true and p.role in ('patient','staff','admin')) then
    raise exception 'An active ERecPass account is required.' using errcode='42501';
  end if;
  select a.* into v_schedule
  from public.staff_availability a
  join public.staff s on s.id=a.staff_id and s.active=true
  join public.profiles p on p.id=s.user_id and p.role='staff' and p.active=true
  where a.staff_id=p_staff_id
    and a.day_of_week=extract(dow from p_appointment_date)::smallint
    and a.is_available=true;
  if not found then return; end if;

  v_slot:=v_schedule.start_time;
  while (p_appointment_date+v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes))::date=p_appointment_date
    and v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes)<=v_schedule.end_time loop
    v_slot_end:=v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes);
    if (p_appointment_date+v_slot)>(now() at time zone 'Asia/Manila')
       and not (v_schedule.break_start is not null and v_slot<v_schedule.break_end and v_slot_end>v_schedule.break_start)
       and not exists(select 1 from public.staff_unavailability u
         where u.staff_id=p_staff_id and u.unavailable_date=p_appointment_date
           and (u.start_time is null or (v_slot<u.end_time and v_slot_end>u.start_time))) then
      select count(*) into v_booked from public.appointments a
      where a.provider_staff_id=p_staff_id and a.appointment_date=p_appointment_date
        and a.appointment_time=v_slot and lower(trim(a.status)) in ('pending','pending approval','approved');
      if v_booked<v_schedule.max_appointments_per_slot and not exists(
        select 1 from public.appointments a
        where a.provider_staff_id=p_staff_id and a.appointment_date=p_appointment_date
          and a.appointment_time is not null and a.appointment_time<>v_slot
          and lower(trim(a.status)) in ('pending','pending approval','approved')
          and a.appointment_time<v_slot_end
          and (a.appointment_time+make_interval(mins=>coalesce(a.appointment_duration_minutes,v_schedule.appointment_duration_minutes)))>v_slot
      ) then
        appointment_time:=v_slot;
        remaining_capacity:=v_schedule.max_appointments_per_slot-v_booked;
        return next;
      end if;
    end if;
    v_slot:=v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes);
  end loop;
end $$;

-- Patient-facing time list across all active providers. The patient chooses a
-- preferred time only; the booking function assigns a provider server-side.
create or replace function public.get_available_appointment_times(
  p_appointment_date date
) returns table(preferred_time time)
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_schedule record;
  v_slot time;
  v_slot_end time;
  v_booked integer;
  v_seen_times time[]:=array[]::time[];
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode='28000'; end if;
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='patient' and p.active=true) then
    raise exception 'Active Patient access is required.' using errcode='42501';
  end if;
  if p_appointment_date is null or p_appointment_date<(now() at time zone 'Asia/Manila')::date then return; end if;

  for v_schedule in
    select a.*,s.id as provider_id
    from public.staff_availability a
    join public.staff s on s.id=a.staff_id and s.active=true
    join public.profiles p on p.id=s.user_id and p.role='staff' and p.active=true
    where a.day_of_week=extract(dow from p_appointment_date)::smallint and a.is_available=true
    order by s.id
  loop
    v_slot:=v_schedule.start_time;
    while (p_appointment_date+v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes))::date=p_appointment_date
      and v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes)<=v_schedule.end_time loop
      v_slot_end:=v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes);
      if (p_appointment_date+v_slot)>(now() at time zone 'Asia/Manila')
         and not (v_schedule.break_start is not null and v_slot<v_schedule.break_end and v_slot_end>v_schedule.break_start)
         and not exists(select 1 from public.staff_unavailability u
           where u.staff_id=v_schedule.provider_id and u.unavailable_date=p_appointment_date
             and (u.start_time is null or (v_slot<u.end_time and v_slot_end>u.start_time))) then
        select count(*) into v_booked from public.appointments a
        where a.provider_staff_id=v_schedule.provider_id and a.appointment_date=p_appointment_date
          and a.appointment_time=v_slot and lower(trim(a.status)) in ('pending','pending approval','approved');
        if v_booked<v_schedule.max_appointments_per_slot and not exists(
          select 1 from public.appointments a
          where a.provider_staff_id=v_schedule.provider_id and a.appointment_date=p_appointment_date
            and a.appointment_time is not null and a.appointment_time<>v_slot
            and lower(trim(a.status)) in ('pending','pending approval','approved')
            and a.appointment_time<v_slot_end
            and (a.appointment_time+make_interval(mins=>coalesce(a.appointment_duration_minutes,v_schedule.appointment_duration_minutes)))>v_slot
        ) and not (v_slot=any(v_seen_times)) then
          preferred_time:=v_slot;
          v_seen_times:=array_append(v_seen_times,v_slot);
          return next;
        end if;
      end if;
      v_slot:=v_slot+make_interval(mins=>v_schedule.appointment_duration_minutes);
    end loop;
  end loop;
end $$;

-- Assign the request to an available provider atomically on the server.
create or replace function public.create_appointment_request(
  p_appointment_date date,
  p_appointment_time time,
  p_reason text
) returns public.appointments
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_patient public.patients%rowtype;
  v_provider record;
  v_end_time time;
  v_booked integer;
  v_appointment public.appointments%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode='28000'; end if;
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='patient' and p.active=true) then
    raise exception 'Active Patient access is required.' using errcode='42501';
  end if;
  if p_appointment_date is null or p_appointment_time is null
     or (p_appointment_date+p_appointment_time)<=(now() at time zone 'Asia/Manila') then
    raise exception 'Choose a future appointment date and time (Asia/Manila).' using errcode='22023';
  end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null or length(trim(p_reason))>1000 then
    raise exception 'Enter a consultation purpose of 1 to 1000 characters.' using errcode='22023';
  end if;
  select p.* into v_patient from public.patients p where p.user_id=auth.uid() and p.active=true;
  if not found then raise exception 'Your active Patient record could not be found.' using errcode='P0002'; end if;

  for v_provider in
    select s.id,s.name,a.appointment_duration_minutes,a.max_appointments_per_slot,
      (select count(*) from public.appointments ap where ap.provider_staff_id=s.id
        and ap.appointment_date=p_appointment_date
        and lower(trim(ap.status)) in ('pending','pending approval','approved')) as booked_today
    from public.staff_availability a
    join public.staff s on s.id=a.staff_id and s.active=true
    join public.profiles pr on pr.id=s.user_id and pr.role='staff' and pr.active=true
    where a.day_of_week=extract(dow from p_appointment_date)::smallint and a.is_available=true
      and p_appointment_time>=a.start_time
      and (p_appointment_date+p_appointment_time+make_interval(mins=>a.appointment_duration_minutes))::date=p_appointment_date
      and p_appointment_time+make_interval(mins=>a.appointment_duration_minutes)<=a.end_time
      and mod(extract(epoch from (p_appointment_time-a.start_time))::integer,a.appointment_duration_minutes*60)=0
      and not (a.break_start is not null and p_appointment_time<a.break_end
        and p_appointment_time+make_interval(mins=>a.appointment_duration_minutes)>a.break_start)
      and not exists(select 1 from public.staff_unavailability u where u.staff_id=s.id
        and u.unavailable_date=p_appointment_date
        and (u.start_time is null or (p_appointment_time<u.end_time
          and p_appointment_time+make_interval(mins=>a.appointment_duration_minutes)>u.start_time)))
    order by booked_today,s.id
  loop
    perform pg_advisory_xact_lock(hashtextextended(v_provider.id||'|'||p_appointment_date::text,0));
    v_end_time:=p_appointment_time+make_interval(mins=>v_provider.appointment_duration_minutes);
    select count(*) into v_booked from public.appointments a
    where a.provider_staff_id=v_provider.id and a.appointment_date=p_appointment_date
      and a.appointment_time=p_appointment_time
      and lower(trim(a.status)) in ('pending','pending approval','approved');
    if v_booked>=v_provider.max_appointments_per_slot then continue; end if;
    if exists(select 1 from public.appointments a
      where a.provider_staff_id=v_provider.id and a.appointment_date=p_appointment_date
        and a.appointment_time is not null and a.appointment_time<>p_appointment_time
        and lower(trim(a.status)) in ('pending','pending approval','approved')
        and a.appointment_time<v_end_time
        and (a.appointment_time+make_interval(mins=>coalesce(a.appointment_duration_minutes,v_provider.appointment_duration_minutes)))>p_appointment_time
    ) then continue; end if;

    insert into public.appointments(
      legacy_id,patient_id,patient_name,doctor,provider_staff_id,appointment_date,
      appointment_time,appointment_duration_minutes,reason,status,created_by
    ) values(
      gen_random_uuid()::text,v_patient.id,v_patient.full_name,v_provider.name,v_provider.id,
      p_appointment_date,p_appointment_time,v_provider.appointment_duration_minutes,
      trim(p_reason),'Pending Approval',auth.uid()
    ) returning * into v_appointment;
    insert into public.appointment_notifications(patient_id,appointment_id,title,message,notification_type)
    values(v_patient.id,v_appointment.id,'Appointment request submitted',
      format('Your appointment request for %s at %s has been submitted and is awaiting approval.',
        to_char(p_appointment_date,'FMMonth DD, YYYY'),to_char(p_appointment_time,'FMHH12:MI AM')||' Manila time'),'pending');
    return v_appointment;
  end loop;
  raise exception 'That preferred time is no longer available. Choose another time.' using errcode='23P01';
end $$;

create or replace function public.staff_decide_appointment(
  p_appointment_id bigint,p_decision text,p_reason text default null,p_note text default null,
  p_appointment_time time default null
) returns public.appointments
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_staff_id text;
  v_appt public.appointments%rowtype;
  v_updated public.appointments%rowtype;
  v_decision text:=lower(trim(coalesce(p_decision,'')));
  v_new_status text;
  v_message text;
  v_provider_name text;
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode='28000'; end if;
  if v_decision not in ('approve','reject') then raise exception 'Decision must be approve or reject.' using errcode='22023'; end if;
  if v_decision='reject' and nullif(trim(coalesce(p_reason,'')),'') is null then
    raise exception 'A rejection reason is required.' using errcode='22023';
  end if;
  select s.id into v_staff_id from public.staff s join public.profiles p on p.id=s.user_id
  where s.user_id=auth.uid() and s.active=true and p.role='staff' and p.active=true;
  if v_staff_id is null then raise exception 'Active Staff access is required.' using errcode='42501'; end if;

  select * into v_appt from public.appointments where id=p_appointment_id for update;
  if not found then raise exception 'Appointment not found.' using errcode='P0002'; end if;
  if v_appt.provider_staff_id is distinct from v_staff_id then
    raise exception 'This appointment is not assigned to your account.' using errcode='42501';
  end if;
  if lower(trim(v_appt.status)) not in ('pending','pending approval') then
    raise exception 'Only pending appointments can be decided.' using errcode='55000';
  end if;
  if v_decision='approve' and v_appt.appointment_time is null and p_appointment_time is null then
    raise exception 'Choose an available appointment time before approving this request.' using errcode='22023';
  end if;

  v_new_status:=case when v_decision='approve' then 'Approved' else 'Rejected' end;
  update public.appointments set status=v_new_status,
    appointment_time=coalesce(p_appointment_time,appointment_time),
    rejection_reason=case when v_decision='reject' then trim(p_reason) else null end,
    staff_note=coalesce(nullif(trim(p_note),''),staff_note),
    last_decision_by=auth.uid(),last_decision_at=now()
  where id=p_appointment_id returning * into v_updated;

  insert into public.appointment_audit_logs(appointment_id,changed_by,changed_by_role,previous_status,new_status,action,reason)
  values(v_appt.id,auth.uid(),'staff',v_appt.status,v_updated.status,'staff_'||v_decision,
    case when v_decision='reject' then trim(p_reason) else coalesce(nullif(trim(p_note),''),'Approved by assigned staff.') end);
  select s.name into v_provider_name from public.staff s where s.id=v_staff_id;
  if v_decision='approve' then
    v_message:=format('Your appointment with %s has been approved for %s%s.',
      coalesce(v_provider_name,v_appt.doctor,'your provider'),
      coalesce(to_char(v_updated.appointment_date,'FMMonth DD, YYYY'),'the selected date'),
      case when v_updated.appointment_time is null then '' else ' at '||to_char(v_updated.appointment_time,'FMHH12:MI AM') end);
  else v_message:='Your appointment request has been rejected. Reason: '||trim(p_reason);
  end if;
  insert into public.appointment_notifications(patient_id,appointment_id,title,message,notification_type)
  values(v_appt.patient_id,v_appt.id,'Appointment '||v_new_status,v_message,lower(v_new_status));
  return v_updated;
end $$;

create or replace function public.cancel_own_appointment(p_appointment_id bigint)
returns public.appointments
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_appt public.appointments%rowtype;
  v_updated public.appointments%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode='28000'; end if;
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='patient' and p.active=true) then
    raise exception 'Active Patient access is required.' using errcode='42501';
  end if;
  select a.* into v_appt from public.appointments a
  join public.patients p on p.id=a.patient_id
  where a.id=p_appointment_id and p.user_id=auth.uid()
  for update of a;
  if not found then raise exception 'Your appointment was not found.' using errcode='P0002'; end if;
  if lower(trim(v_appt.status)) not in ('pending','pending approval','approved') then
    raise exception 'Only pending or approved appointments can be cancelled.' using errcode='55000';
  end if;
  update public.appointments set status='Cancelled',last_decision_by=auth.uid(),last_decision_at=now()
  where id=p_appointment_id returning * into v_updated;
  insert into public.appointment_audit_logs(appointment_id,changed_by,changed_by_role,previous_status,new_status,action,reason)
  values(v_appt.id,auth.uid(),'patient',v_appt.status,v_updated.status,'patient_cancel','Cancelled by patient.');
  insert into public.appointment_notifications(patient_id,appointment_id,title,message,notification_type)
  values(v_appt.patient_id,v_appt.id,'Appointment cancelled','Your appointment has been cancelled.','cancelled');
  return v_updated;
end $$;

create or replace function public.admin_override_appointment(
  p_appointment_id bigint,p_new_status text,p_reason text,p_provider_staff_id text default null,
  p_appointment_date date default null,p_appointment_time time default null
) returns public.appointments
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_appt public.appointments%rowtype;
  v_updated public.appointments%rowtype;
  v_provider_name text;
  v_message text;
  v_schedule_changed boolean;
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode='28000'; end if;
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin' and p.active=true) then
    raise exception 'Active Admin access is required.' using errcode='42501';
  end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception 'An override reason is required.' using errcode='22023'; end if;
  if p_new_status not in ('Pending Approval','Pending','Approved','Rejected','Cancelled','Completed') then
    raise exception 'Unsupported appointment status.' using errcode='22023';
  end if;
  select * into v_appt from public.appointments where id=p_appointment_id for update;
  if not found then raise exception 'Appointment not found.' using errcode='P0002'; end if;

  v_schedule_changed:=(p_provider_staff_id is not null and p_provider_staff_id is distinct from v_appt.provider_staff_id)
    or (p_appointment_date is not null and p_appointment_date is distinct from v_appt.appointment_date)
    or (p_appointment_time is not null and p_appointment_time is distinct from v_appt.appointment_time);
  update public.appointments set status=p_new_status,
    provider_staff_id=coalesce(p_provider_staff_id,provider_staff_id),
    appointment_date=coalesce(p_appointment_date,appointment_date),
    appointment_time=coalesce(p_appointment_time,appointment_time),
    rejection_reason=case when p_new_status='Rejected' then trim(p_reason) else null end,
    last_decision_by=auth.uid(),last_decision_at=now()
  where id=p_appointment_id returning * into v_updated;
  insert into public.appointment_audit_logs(appointment_id,changed_by,changed_by_role,previous_status,new_status,action,reason)
  values(v_appt.id,auth.uid(),'admin',v_appt.status,v_updated.status,
    case when v_schedule_changed then 'admin_reschedule_or_reassign' else 'admin_override' end,trim(p_reason));

  if v_appt.status is distinct from v_updated.status or v_schedule_changed then
    select s.name into v_provider_name from public.staff s where s.id=v_updated.provider_staff_id;
    v_message:=case
      when v_updated.status='Approved' then format('Your appointment with %s has been approved for %s%s.',
        coalesce(v_provider_name,v_updated.doctor,'your provider'),
        coalesce(to_char(v_updated.appointment_date,'FMMonth DD, YYYY'),'the selected date'),
        case when v_updated.appointment_time is null then '' else ' at '||to_char(v_updated.appointment_time,'FMHH12:MI AM') end)
      when v_updated.status='Rejected' then 'Your appointment request has been rejected. Reason: '||trim(p_reason)
      when v_updated.status='Cancelled' then 'Your appointment has been cancelled. Reason: '||trim(p_reason)
      when v_schedule_changed then format('Your appointment has been rescheduled to %s%s.',
        coalesce(to_char(v_updated.appointment_date,'FMMonth DD, YYYY'),'the selected date'),
        case when v_updated.appointment_time is null then '' else ' at '||to_char(v_updated.appointment_time,'FMHH12:MI AM') end)
      else 'Your appointment status is now '||v_updated.status||'. Reason: '||trim(p_reason)
    end;
    insert into public.appointment_notifications(patient_id,appointment_id,title,message,notification_type)
    values(v_updated.patient_id,v_updated.id,'Appointment update',v_message,
      case when v_schedule_changed then 'rescheduled' else lower(v_updated.status) end);
  end if;
  return v_updated;
end $$;

